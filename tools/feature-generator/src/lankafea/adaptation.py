# Anchor coverage validation (Glyphs sources only — binaries lack anchor data)
# ---------------------------------------------------------------------------

# Anchor families a Sinhala font uses for mark attachment (Noto vocabulary).
_MARK_ANCHOR_OF_SIGN = {
    "usign": "uvowel", "uusign": "uvowel",
    "isign": "iVowel", "iisign": "iiVowel",
    "virama": "alSign",
    "repha": "repaya",
    "rasign": "rakar",
}


def anchor_findings(inventory: FontInventory, satisfied_sign_counts: dict[str, int],
                    profile: ScriptProfile) -> list[str]:
    """For signs the font does NOT cover with precomposed ligatures, check the
    anchor pairing that GPOS mark attachment would need."""
    if not inventory.anchors:
        return []          # compiled font or anchor-less source: nothing to say
    ns = profile.namespace
    findings: list[str] = []
    consonant_bases = [f"{stem}a-{ns}" for stem in profile.tables.consonants.values()]

    for sign, base_anchor in _MARK_ANCHOR_OF_SIGN.items():
        sign_glyph = f"{sign}-{ns}"
        if sign_glyph not in inventory.glyphs:
            continue
        lig_count = satisfied_sign_counts.get(sign, 0)
        mark_anchors = inventory.anchors.get(sign_glyph, set())
        has_mark = any(a.startswith("_") for a in mark_anchors)
        carriers = [b for b in consonant_bases if b in inventory.glyphs]
        with_anchor = [b for b in carriers
                       if base_anchor in inventory.anchors.get(b, set())]
        if lig_count == 0 and not has_mark:
            findings.append(
                f"anchor: {sign_glyph} has no precomposed ligatures AND no "
                f"'_' mark anchor — it cannot attach; add '_{base_anchor}' to "
                f"the sign and '{base_anchor}' to bases, or draw ligatures")
        elif has_mark and carriers and len(with_anchor) < len(carriers):
            missing = len(carriers) - len(with_anchor)
            findings.append(
                f"anchor: {sign_glyph} attaches via '_{base_anchor}' but "
                f"{missing}/{len(carriers)} base consonants lack the "
                f"'{base_anchor}' anchor")
    return findings


def satisfied_sign_counts(checks, profile: ScriptProfile) -> dict[str, int]:
    """How many satisfiable rules consume each standalone sign as an input."""
    ns_suffix = f"-{profile.namespace}"
    counts: dict[str, int] = {}
    sign_names = set(profile.tables.sign_alone.values()) | {"repha", "rasign", "yasign"}
    for check in checks:
        if not check.satisfiable:
            continue
        for token in check.rule.inputs:
            t = token[:-1] if token.endswith("'") else token
            if t.startswith("@") or not t.endswith(ns_suffix):
                continue
            stem = t[: -len(ns_suffix)]
            if stem in sign_names:
                counts[stem] = counts.get(stem, 0) + 1
    return counts
